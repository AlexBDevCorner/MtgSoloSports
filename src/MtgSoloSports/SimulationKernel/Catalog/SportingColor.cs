namespace MtgSoloSports.SimulationKernel.Catalog;

/// <summary>
/// The eight sporting colors from Game Rules v1, based on printed card color
/// rather than color identity. Order matches the rules document.
/// </summary>
public enum SportingColor
{
    White = 0,
    Blue = 1,
    Black = 2,
    Red = 3,
    Green = 4,
    Multicolor = 5,
    Hybrid = 6,
    Colorless = 7,
}
